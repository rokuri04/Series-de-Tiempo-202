required_columns = ['Date', 'Close']
for df, name in [(nu_df, 'NU'), (microsoft_df, 'Microsoft')]:
    if not all(col in df.columns for col in required_columns):
        raise KeyError(f"Faltan columnas requeridas en el DataFrame de {name}. Esperado: {required_columns}")

