# Prueba de Estacionariedad (Prueba ADF)
def adf_test(series, name):
    result = adfuller(series.dropna())
    print(f'Prueba ADF para {name}:')
    print(f'Estadístico ADF: {result[0]}')
    print(f'valor-p: {result[1]}')
    print('Estacionario' if result[1] < 0.05 else 'No Estacionario')
    return result[1] < 0.05

# Realizar la prueba ADF en las series originales
nu_stationary = adf_test(nu_df['Close'], 'NU')
microsoft_stationary = adf_test(microsoft_df['Close'], 'Microsoft')

# Diferenciar si no es estacionario
nu_diff = nu_df['Close'].diff().dropna() if not nu_stationary else nu_df['Close']
microsoft_diff = microsoft_df['Close'].diff().dropna() if not microsoft_stationary else microsoft_df['Close']

# Graficar la serie diferenciada si se aplicó
if not nu_stationary or not microsoft_stationary:
    plt.figure(figsize=(12, 6))
    plt.plot(nu_diff, label='NU Diferenciada')
    plt.plot(microsoft_diff, label='Microsoft Diferenciada')
    plt.title('Precios de Acciones Diferenciados (5-Minutos)')
    plt.xlabel('Tiempo')
    plt.ylabel('Diferencia de Precio')
    plt.legend()
    plt.grid(True)
    plt.show()

# Volver a probar la estacionariedad en las series diferenciadas
if not nu_stationary:
    adf_test(nu_diff, 'NU Diferenciada')
if not microsoft_stationary:
    adf_test(microsoft_diff, 'Microsoft Diferenciada')

# Prueba de Cointegración
score, p_value, _ = coint(nu_df['Close'], microsoft_df['Close'])
print(f'Prueba de Cointegración:')
print(f'valor-p: {p_value}')
print('Cointegradas' if p_value < 0.05 else 'No Cointegradas')

# Modelo AR
def fit_ar_model(series, name, lags=5):
    model = AutoReg(series, lags=lags).fit()
    print(f'Modelo AR({lags}) para {name}:')
    print(model.summary())

    # Pronóstico
    forecast = model.predict(start=len(series), end=len(series)+1)  # 10 minutos = 2 pasos a 5-min de frecuencia

    # Gráfico
    plt.figure(figsize=(12, 6))
    plt.plot(series[-50:], label='Actual')
    forecast_index = pd.date_range(start=series.index[-1] + timedelta(minutes=5), periods=2, freq='5T')
    plt.plot(forecast_index, forecast, label='Pronóstico', linestyle='--')
    plt.title(f'Pronóstico AR({lags}) para {name} (10-Minutos Adelante)')
    plt.xlabel('Tiempo')
    plt.ylabel('Precio de Cierre')
    plt.legend()
    plt.grid(True)
    plt.show()

    return model

# Ajustar modelos AR
nu_ar = fit_ar_model(nu_diff, 'NU')
microsoft_ar = fit_ar_model(microsoft_diff, 'Microsoft')

# Modelo ARMA (asumiendo ARMA(2,2))
def fit_arma_model(series, name, order=(2,2)):
    model = ARIMA(series, order=(order[0], 0, order[1])).fit()
    print(f'Modelo ARMA({order[0]},{order[1]}) para {name}:')
    print(model.summary())

    # Pronóstico
    forecast = model.forecast(steps=2)  # 10 minutos = 2 pasos a 5-min de frecuencia

    # Gráfico
    plt.figure(figsize=(12, 6))
    plt.plot(series[-50:], label='Actual')
    forecast_index = pd.date_range(start=series.index[-1] + timedelta(minutes=5), periods=2, freq='5T')
    plt.plot(forecast_index, forecast, label='Pronóstico', linestyle='--')
    plt.title(f'Pronóstico ARMA({order[0]},{order[1]}) para {name} (10-Minutos Adelante)')
    plt.xlabel('Tiempo')
    plt.ylabel('Precio de Cierre')
    plt.legend()
    plt.grid(True)
    plt.show()

    return model

# Ajustar modelos ARMA
nu_arma = fit_arma_model(nu_diff, 'NU')
microsoft_arma = fit_arma_model(microsoft_diff, 'Microsoft')

