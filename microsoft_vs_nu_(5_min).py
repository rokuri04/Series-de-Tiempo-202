# Función para convertir fechas de Excel a datetime (si es numérico)
def excel_date_to_datetime(excel_date):
    if pd.api.types.is_numeric_dtype(excel_date):
        return pd.to_datetime('1899-12-30') + pd.to_timedelta(excel_date, unit='D')
    return excel_date  # Retorna tal cual si ya es datetime

