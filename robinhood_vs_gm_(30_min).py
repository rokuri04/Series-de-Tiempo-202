# Prueba de Estacionariedad (Prueba ADF)
def adf_test(series, name):
    result = adfuller(series.dropna())
    print(f'Prueba ADF para {name}:')
    print(f'Estadístico ADF: {result[0]}')
    print(f'valor-p: {result[1]}')
    print('Estacionario' if result[1] < 0.05 else 'No Estacionario')
    return result[1] < 0.05

# Realizar la prueba ADF en las series originales
robinhood_stationary = adf_test(robinhood_df['Close'], 'Robinhood')
gm_stationary = adf_test(gm_df['Close'], 'General Motors')

# Diferenciar si no es estacionario
robinhood_diff = robinhood_df['Close'].diff().dropna() if not robinhood_stationary else robinhood_df['Close']
gm_diff = gm_df['Close'].diff().dropna() if not gm_stationary else gm_df['Close']

# Graficar la serie diferenciada si se aplicó
if not robinhood_stationary or not gm_stationary:
    plt.figure(figsize=(12, 6))
    plt.plot(robinhood_diff, label='Robinhood Diferenciada')
    plt.plot(gm_diff, label='General Motors Diferenciada')
    plt.title('Precios de Acciones Diferenciados (30-Minutos)')
    plt.xlabel('Tiempo')
    plt.ylabel('Diferencia de Precio')
    plt.legend()
    plt.grid(True)
    plt.show()

# Volver a probar la estacionariedad en las series diferenciadas
if not robinhood_stationary:
    adf_test(robinhood_diff, 'Robinhood Diferenciada')
if not gm_stationary:
    adf_test(gm_diff, 'General Motors Diferenciada')

# Prueba de Cointegración
