print(f'Prueba de Cointegración:')
print(f'valor-p: {p_value}')
print('Cointegradas' if p_value < 0.05 else 'No Cointegradas')

# Modelo AR
def fit_ar_model(series, name, lags=5):
    model = AutoReg(series, lags=lags).fit()
    print(f'Modelo AR({lags}) para {name}:')
    print(model.summary())

    # Pronóstico: 10 minutos es menos de 30 minutos, así que pronosticamos 1 paso (próximo intervalo de 30 minutos)
    forecast = model.predict(start=len(series), end=len(series))  # 1 paso a 30-min de frecuencia

    # Gráfico
    plt.figure(figsize=(12, 6))
    plt.plot(series[-50:], label='Actual')
    forecast_index = pd.date_range(start=series.index[-1] + timedelta(minutes=30), periods=1, freq='30T')
    plt.plot(forecast_index, forecast, label='Pronóstico', linestyle='--')
    plt.title(f'Pronóstico AR({lags}) para {name} (Próximo Intervalo de 30 Minutos)')
    plt.xlabel('Tiempo')
    plt.ylabel('Precio de Cierre')
    plt.legend()
    plt.grid(True)
    plt.show()

    return model

# Ajustar modelos AR
robinhood_ar = fit_ar_model(robinhood_diff, 'Robinhood')
gm_ar = fit_ar_model(gm_diff, 'General Motors')

# Modelo ARMA (asumiendo ARMA(2,2))
def fit_arma_model(series, name, order=(2,2)):
    model = ARIMA(series, order=(order[0], 0, order[1])).fit()
    print(f'Modelo ARMA({order[0]},{order[1]}) para {name}:')
    print(model.summary())

    # Pronóstico: 1 paso a 30-min de frecuencia
    forecast = model.forecast(steps=1)

    # Gráfico
    plt.figure(figsize=(12, 6))
    plt.plot(series[-50:], label='Actual')
    forecast_index = pd.date_range(start=series.index[-1] + timedelta(minutes=30), periods=1, freq='30T')
    plt.plot(forecast_index, forecast, label='Pronóstico', linestyle='--')
    plt.title(f'Pronóstico ARMA({order[0]},{order[1]}) para {name} (Próximo Intervalo de 30 Minutos)')
    plt.xlabel('Tiempo')
    plt.ylabel('Precio de Cierre')
    plt.legend()
    plt.grid(True)
    plt.show()

    return model

# Ajustar modelos ARMA
robinhood_arma = fit_arma_model(robinhood_diff, 'Robinhood')
gm_arma = fit_arma_model(gm_diff, 'General Motors')

